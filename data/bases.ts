export function getBasesByBranch(branch: Branch): Base[] {
  return bases.filter(b => b.branch === branch).sort((a, b) => a.name.localeCompare(b.name));
}

export function getBaseBySlug(slug: string): Base | undefined {
  return bases.find(b => b.slug === slug);
}
